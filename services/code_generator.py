import os
from typing import Dict, Any, List, Optional
from django.db import transaction
from apps.projects.models import Project, ProjectFile, PromptIteration
from .gemini_service import GeminiService
from .file_manager import FileManager


class CodeGeneratorService:
    """
    Coordinates AI generation, file validation, disk writing, and DB record persistence.
    """

    @classmethod
    def generate_project(cls, project: Project) -> bool:
        """
        Executes code generation for a newly created Project model.
        Updates status to 'generating', invokes Gemini, persists files, and marks 'completed'.
        """
        project.status = 'generating'
        project.save(update_fields=['status'])

        try:
            # 1. Call Gemini Service
            ai_data = GeminiService.generate_application(
                prompt=project.original_prompt,
                category=project.category
            )

            # 2. Extract metadata
            if ai_data.get('project_title') and project.title == 'Untitled Project':
                project.title = ai_data['project_title']
            if ai_data.get('project_summary'):
                project.description = ai_data['project_summary']
            if ai_data.get('category'):
                project.category = ai_data['category']

            files_data = ai_data.get('files', [])
            if not files_data:
                raise ValueError("No files were generated by the AI engine.")

            # Validate mandatory entrypoint
            has_html = any(f.get('path', '').endswith('.html') for f in files_data)
            if not has_html:
                # Provide fallback minimal index.html
                files_data.append({
                    'path': 'index.html',
                    'file_type': 'html',
                    'content': f"<!DOCTYPE html><html><head><title>{project.title}</title></head><body><h1>{project.title}</h1><p>{project.description}</p></body></html>"
                })

            # 3. Write files to disk and DB atomically
            with transaction.atomic():
                # Clear any existing file records if re-generating
                project.files.all().delete()

                for f in files_data:
                    rel_path = f.get('path', '').strip().replace('\\', '/')
                    content = f.get('content', '')
                    f_type = f.get('file_type', '')

                    # Write to disk with path traversal guard
                    FileManager.write_file(project.storage_dir, rel_path, content)

                    # Save to DB
                    ProjectFile.objects.create(
                        project=project,
                        relative_path=rel_path,
                        content=content,
                        file_type=f_type
                    )

                # Record first iteration
                PromptIteration.objects.create(
                    project=project,
                    iteration_number=1,
                    prompt=project.original_prompt,
                    summary_of_changes="Initial application generation.",
                    model_used=GeminiService.get_api_key() and "gemini-2.5-flash" or "synthesizer"
                )

                project.status = 'completed'
                project.save()

            return True

        except Exception as e:
            project.status = 'failed'
            project.error_message = str(e)
            project.save(update_fields=['status', 'error_message'])
            return False

    @classmethod
    def iterate_project(cls, project: Project, modification_prompt: str) -> bool:
        """
        Updates an existing project with a follow-up modification prompt.
        """
        project.status = 'generating'
        project.save(update_fields=['status'])

        try:
            # 1. Fetch current files
            existing_files = [
                {'path': pf.relative_path, 'content': pf.content, 'file_type': pf.file_type}
                for pf in project.files.all()
            ]

            # 2. Call Gemini Service
            ai_data = GeminiService.iterate_application(
                existing_files=existing_files,
                iteration_prompt=modification_prompt,
                project_title=project.title
            )

            updated_files = ai_data.get('files', [])
            if not updated_files:
                raise ValueError("No updated files were returned.")

            # 3. Write files to disk and DB atomically
            with transaction.atomic():
                for f in updated_files:
                    rel_path = f.get('path', '').strip().replace('\\', '/')
                    content = f.get('content', '')
                    f_type = f.get('file_type', '')

                    # Update disk
                    FileManager.write_file(project.storage_dir, rel_path, content)

                    # Update or create DB record
                    ProjectFile.objects.update_or_create(
                        project=project,
                        relative_path=rel_path,
                        defaults={
                            'content': content,
                            'file_type': f_type
                        }
                    )

                # Increment version
                new_version = project.version + 1
                project.version = new_version
                project.status = 'completed'
                project.save(update_fields=['version', 'status', 'updated_at'])

                # Record iteration
                PromptIteration.objects.create(
                    project=project,
                    iteration_number=new_version,
                    prompt=modification_prompt,
                    summary_of_changes=ai_data.get('project_summary', f"Iteration #{new_version}"),
                    model_used=GeminiService.get_api_key() and "gemini-2.5-flash" or "synthesizer"
                )

            return True

        except Exception as e:
            project.status = 'completed'  # Revert to completed on failed iteration so user can continue
            project.error_message = f"Iteration failed: {str(e)}"
            project.save(update_fields=['status', 'error_message'])
            return False
